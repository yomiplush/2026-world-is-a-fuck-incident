// Offline audit: availability follows the actual motion copy, not the shared
// catalog (Tailworm and reading pages have independent translation coverage).
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const marker = '/* Motion translation availability (generated by tools/check-motion-locales.cjs). */';

function audit(root) {
  const scope = {window: {}};
  vm.runInNewContext(fs.readFileSync(path.join(root, 'site/data.js'), 'utf8'), scope);
  const content = scope.window.CONTENT;
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'content/site-languages.json'), 'utf8')).languages;
  const technical = text => (text.match(/CVE-\d{4}-\d+|GHSA-[a-z0-9]{4}(?:-[a-z0-9]{4}){2}|v?\d+(?:\.\d+)+/g) || []).sort();
  const hrefs = text => Array.from(text.matchAll(/href=["']([^"']+)["']/g), match => match[1]).sort();
  const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  const joined = copy => [copy.kicker, copy.title, copy.lede, ...copy.points].join('\n');
  const status = {};
  for (const language of catalog) {
    const code = language.code;
    let locale;
    if (['ja', 'en'].includes(code)) {
      locale = {ui: content.ui[code], scenes: Object.fromEntries(content.scenes.map(scene =>
        [scene.id, {...scene[code], metric: scene.metric?.label[code]}]))};
    } else {
      try {
        vm.runInNewContext(fs.readFileSync(path.join(root, 'site/i18n', code + '.js'), 'utf8'), {
          window: {registerLocale(registered, data) { if (registered === code) locale = data; }}
        });
      } catch (_) { /* Invalid or absent assets remain unavailable. */ }
    }
    const translated = content.scenes.filter(scene => typeof locale?.scenes?.[scene.id]?.title === 'string').length;
    const ready = !!locale?.ui && Object.keys(content.ui.en).every(key => typeof locale.ui[key] === 'string') &&
      content.scenes.every(scene => {
        const copy = locale.scenes?.[scene.id];
        if (!copy || typeof copy.title !== 'string' || !copy.title.trim() ||
            typeof copy.kicker !== 'string' || typeof copy.lede !== 'string' ||
            !Array.isArray(copy.points) || copy.points.length !== scene.en.points.length ||
            !copy.points.every(point => typeof point === 'string') ||
            (scene.metric && typeof copy.metric !== 'string')) return false;
        if (!['ja', 'en'].includes(code) && scene.en.lede && copy.lede === scene.en.lede) return false;
        return code === 'ja' || (equal(technical(joined(copy)), technical(joined(scene.en))) &&
          equal(hrefs(joined(copy)), hrefs(joined(scene.en))));
      });
    status[code] = {ready, translated, total: content.scenes.length};
  }
  return status;
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..');
  const status = audit(root);
  const file = path.join(root, 'site/data.js');
  const existing = fs.readFileSync(file, 'utf8');
  const generated = existing.split(marker)[0].trimEnd() + '\n\n' + marker +
    '\nwindow.MOTION_LOCALE_STATUS = ' + JSON.stringify(status, null, 2) + ';\n';
  if (process.argv.includes('--write')) fs.writeFileSync(file, generated);
  else if (existing !== generated) {
    console.error('Motion locale availability is stale. Run node tools/check-motion-locales.cjs --write.');
    process.exitCode = 1;
  }
  console.log(JSON.stringify(status));
}
module.exports = {audit};
